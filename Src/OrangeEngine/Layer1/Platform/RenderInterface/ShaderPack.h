#ifndef SHADER_PACK_H
#define SHADER_PACK_H

#include "Shader.h"
#include <filesystem>

namespace Orange
{
    /**
     * @class ShaderPack
     * @brief 着色器包管理类
     *
     * 这个类提供了着色器包的管理功能，包括着色器的打包、加载
     * 和查询。着色器包是一种优化的着色器存储格式，将多个预编译
     * 的着色器存储在单个文件中，以提高加载性能。
     *
     * 主要功能包括：
     * - 着色器包加载：从文件加载预编译的着色器包
     * - 着色器查询：检查包中是否包含指定的着色器
     * - 着色器提取：从包中加载特定的着色器实例
     * - 包创建：从着色器库创建新的着色器包
     * - 状态管理：跟踪包的加载状态
     *
     * 着色器包的优势：
     * - 性能提升：避免运行时编译，显著减少加载时间
     * - 存储优化：压缩存储，减少磁盘空间占用
     * - 分发便利：单文件包含所有着色器，便于分发
     * - 版本控制：支持着色器版本管理和兼容性检查
     * - 缓存友好：减少文件I/O操作，提高缓存效率
     *
     * 文件格式：
     * 着色器包使用自定义的二进制格式，包含：
     * - 文件头：版本信息、着色器数量等元数据
     * - 索引区：着色器名称到数据的映射表
     * - 反射数据：着色器的反射信息和元数据
     * - 模块数据：预编译的着色器字节码
     *
     * 使用场景：
     * - 生产环境：预编译着色器以提高启动速度
     * - 内容分发：将着色器打包用于游戏分发
     * - 版本管理：管理不同版本的着色器集合
     * - 平台优化：为特定平台优化的着色器包
     *
     * 工作流程：
     * 1. 开发阶段：使用源代码着色器进行开发和调试
     * 2. 构建阶段：将着色器库编译并打包成着色器包
     * 3. 运行阶段：从着色器包快速加载预编译的着色器
     * 4. 分发阶段：将着色器包作为资源文件分发
     *
     * 性能考虑：
     * - 内存使用：着色器包在内存中保持索引信息
     * - 加载速度：预编译着色器避免了运行时编译开销
     * - 缓存效率：减少文件系统访问次数
     * - 启动时间：显著减少应用程序启动时间
     */
    class ShaderPack : public RefCounted
    {
    public:
        /**
         * @brief 默认构造函数
         *
         * 创建一个空的着色器包实例，需要后续加载或创建内容。
         */
        ShaderPack() = default;

        /**
         * @brief 从文件构造着色器包
         * @param path 着色器包文件路径
         *
         * 从指定的文件路径加载着色器包。构造函数会读取文件头
         * 和索引信息，但不会立即加载所有着色器数据。
         *
         * 加载过程：
         * 1. 验证文件格式和版本
         * 2. 读取文件头信息
         * 3. 构建着色器索引映射
         * 4. 准备延迟加载机制
         *
         * @note 如果文件不存在或格式无效，包将标记为未加载状态
         */
        ShaderPack(const std::filesystem::path &path);

        /**
         * @brief 检查着色器包是否已加载
         * @return 如果着色器包已成功加载则返回true
         *
         * 检查着色器包是否已从文件成功加载并可以使用。
         * 只有加载成功的包才能进行着色器查询和提取操作。
         */
        bool IsLoaded() const { return m_Loaded; }

        /**
         * @brief 检查是否包含指定着色器
         * @param name 着色器名称
         * @return 如果包含指定着色器则返回true
         *
         * 检查着色器包中是否包含指定名称的着色器。
         * 这是一个快速查询操作，只检查索引而不加载着色器数据。
         *
         * 查询过程：
         * 1. 计算着色器名称的哈希值
         * 2. 在索引映射中查找对应条目
         * 3. 返回查找结果
         *
         * @note 此操作不会触发着色器的实际加载
         */
        bool Contains(std::string_view name) const;

        /**
         * @brief 从包中加载着色器
         * @param name 着色器名称
         * @return 加载的着色器实例智能指针
         *
         * 从着色器包中加载指定名称的着色器实例。这个操作会
         * 从文件中读取预编译的着色器数据并创建可用的着色器对象。
         *
         * 加载过程：
         * 1. 验证着色器存在性
         * 2. 读取着色器反射数据
         * 3. 加载预编译的着色器模块
         * 4. 创建着色器实例
         * 5. 设置描述符和资源绑定
         *
         * 性能特点：
         * - 避免了源代码编译过程
         * - 直接使用预编译的字节码
         * - 快速的着色器创建和初始化
         *
         * @note 要求着色器包已加载且包含指定的着色器
         * @note 返回的着色器已完全初始化并可立即使用
         */
        Ref<Shader> LoadShader(std::string_view name);

        /**
         * @brief 从着色器库创建着色器包
         * @param shaderLibrary 源着色器库
         * @param path 输出文件路径
         * @return 创建的着色器包实例智能指针
         *
         * 从现有的着色器库创建一个新的着色器包文件。这个静态方法
         * 用于将开发阶段的着色器库转换为优化的着色器包格式。
         *
         * 创建过程：
         * 1. 分析着色器库中的所有着色器
         * 2. 提取着色器的编译数据和反射信息
         * 3. 构建着色器包的文件结构
         * 4. 序列化数据到文件
         * 5. 创建对应的着色器包实例
         *
         * 文件结构：
         * - 文件头：包含版本和统计信息
         * - 程序索引：着色器名称到数据的映射
         * - 模块索引：着色器模块的位置信息
         * - 反射数据：着色器的元数据和接口信息
         * - 模块数据：预编译的着色器字节码
         *
         * 使用场景：
         * - 构建系统：将开发着色器转换为发布格式
         * - 内容管道：自动化着色器包生成
         * - 版本发布：为特定版本创建着色器包
         * - 平台适配：为不同平台生成优化包
         *
         * 性能考虑：
         * - 这是一个I/O密集型操作
         * - 文件大小取决于着色器数量和复杂度
         * - 建议在构建时而非运行时执行
         *
         * @note 要求源着色器库中的所有着色器都已编译
         * @note 生成的文件可以在相同图形API的环境中使用
         */
        static Ref<ShaderPack> CreateFromLibrary(Ref<ShaderLibrary> shaderLibrary, const std::filesystem::path &path);

    private:
        bool m_Loaded = false; ///< 着色器包加载状态
#ifdef TODO
        ShaderPackFile m_File; ///< 着色器包文件数据结构
#endif
        std::filesystem::path m_Path; ///< 着色器包文件路径
    };
}

#endif